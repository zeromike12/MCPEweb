def render(template, palette):
    lines = [l for l in template.strip('\n').split('\n')]
    assert len(lines) == 16, len(lines)
    out = []
    for l in lines:
        assert len(l) == 16, repr(l)
        row = []
        for ch in l:
            c = palette.get(ch)
            row.append((0, 0, 0, 0) if c is None else (c[0], c[1], c[2], 255))
        out.append(row)
    return out

def blit(rows, col, rowi, sprite):
    for y in range(16):
        for x in range(16):
            r, g, b, a = sprite[y][x]
            o = ((col) + (rowi * 16 + y) * 16 * 16) * 0  # unused
            idx = (col * 16 + x) * 4
            line = rows[rowi * 16 + y]
            line[idx:idx + 4] = bytes((r, g, b, a))

