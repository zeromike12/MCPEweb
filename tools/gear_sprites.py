def main():
    w, h, rows = read_png(ITEMS_PNG)
    assert (w, h) == (256, 256)
    for name, cells in ARMOR_CELLS.items():
        p = SETS[name]
        for (c, r), tpl in zip(cells, [HELMET, CHESTPLATE, LEGGINGS, BOOTS]):
            blit(rows, c, r, render(tpl, p))
    for name, (c, r) in WEAPON_CELLS.items():
        p, tpl = WEAPONS[name]
        blit(rows, c, r, render(tpl, p))
    write_png(ITEMS_PNG, w, h, rows)
    print('updated', ITEMS_PNG)

if __name__ == '__main__':
    main()


# ----------------------------------------------------------------------
# Worn armor textures: recolour data/images/armor/diamond_{1,2}.png per set
# ----------------------------------------------------------------------
def recolour_armor():
    armor_dir = os.path.join(ROOT, 'data', 'images', 'armor')
    for name, p in SETS.items():
        d, m, l, a = p['d'], p['m'], p['l'], p['a']
        for layer in (1, 2):
            w, h, rows = read_png(os.path.join(armor_dir, 'diamond_%d.png' % layer))
            out = []
            for y in range(h):
                line = bytearray(rows[y])
                for x in range(w):
                    r, g, b, al = line[x * 4:x * 4 + 4]
                    if al == 0: continue
                    lum = (r * 299 + g * 587 + b * 114) / 1000.0 / 255.0
                    # map luminance onto the set's dark -> mid -> light ramp
                    if lum < 0.45:
                        t = lum / 0.45; c0, c1 = d, m
                    else:
                        t = (lum - 0.45) / 0.55; c0, c1 = m, l
                    col = tuple(int(c0[i] + (c1[i] - c0[i]) * t) for i in range(3))
                    line[x * 4:x * 4 + 3] = bytes(col)
                out.append(line)
            write_png(os.path.join(armor_dir, '%s_%d.png' % (name, layer)), w, h, out)
            print('wrote', name, layer)

if __name__ == '__main__':
    recolour_armor()
